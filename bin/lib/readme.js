import { expandManifestSkills } from './manifest.js';

const START = '<!-- SKILLS:START -->';
const END = '<!-- SKILLS:END -->';

export function repoLink(repo) {
  return `[${repo}](https://github.com/${repo})`;
}

export function generateSkillsBlock(manifest, lock, options = {}) {
  const now = options.now ?? new Date();
  const date = now.toISOString().slice(0, 10);
  const skills = expandManifestSkills(manifest, lock);
  const sourceCount = new Set(skills.map((s) => s.repo)).size;

  const rows = skills.map(({ name, repo, custom }) => {
    const label = custom ? `${name} (custom)` : name;
    return `| ${label} | ${repoLink(repo)} |`;
  });

  return [
    START,
    '<!-- generated by ckmah-skills — do not edit manually -->',
    '',
    '| Skill | Source |',
    '|-------|--------|',
    ...rows,
    '',
    `**${skills.length} skills** across ${sourceCount} sources. Last updated: ${date}.`,
    '',
    END,
  ].join('\n');
}

export function updateReadmeSkillsSection(readme, manifest, lock, options = {}) {
  const block = generateSkillsBlock(manifest, lock, options);
  const pattern = new RegExp(`${escapeRegExp(START)}[\\s\\S]*?${escapeRegExp(END)}`);
  if (!pattern.test(readme)) {
    throw new Error('README missing SKILLS markers');
  }
  return readme.replace(pattern, block);
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
